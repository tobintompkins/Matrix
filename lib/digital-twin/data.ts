export function getDigitalTwinMachine(
  machineId: string,
): DigitalTwinMachine | undefined {
  const normalized = machineId.trim().toUpperCase();
  return digitalTwinFleet.find(
    (m) =>
      m.identity.machineId.toUpperCase() === normalized ||
      m.identity.assetTag.toUpperCase() === normalized,
  );
}

